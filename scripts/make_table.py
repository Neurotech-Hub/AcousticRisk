"""Build supplementary evidence matrix from the CSV source.

Source of truth: manuscript/tables/evidence_matrix.csv (edit that, not the .tex).
Run from the repository root: python3 scripts/make_table.py

Writes both:
  manuscript/supplement/table_evidence_matrix.tex  (compiled)
  manuscript/tables/table1_evidence.tex            (legacy mirror)
"""
import csv
import re
from pathlib import Path

SRC = Path("manuscript/tables/evidence_matrix.csv")
OUTS = [
    Path("manuscript/supplement/table_evidence_matrix.tex"),
    Path("manuscript/tables/table1_evidence.tex"),
]

# Widths sum with column padding to the 9in landscape text block.
COLUMNS = [
    ("Study", "0.95in", lambda r: rf"\citet{{{r['key']}}}"),
    ("Species", "0.95in", lambda r: tex(r["species"])),
    ("Setting", "0.43in", lambda r: rf"\mbox{{{tex(r['setting'])}}}"),
    ("Receiver experience", "0.75in", lambda r: tex(r["experience"])),
    ("Stimuli", "1.35in", lambda r: tex(r["stimuli"])),
    ("Controls", "0.9in", lambda r: tex(r["controls"])),
    ("Endpoints", "0.95in", lambda r: tex(r["endpoints"])),
    ("Key result", "1.6in", lambda r: tex(r["result"])),
    ("Sec.", "0.32in", lambda r: sections(r.get("sections", r.get("questions", "")))),
]


def tex(s: str) -> str:
    s = s.replace("\\", r"\textbackslash{}")
    for a, b in [("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_")]:
        s = s.replace(a, b)
    s = s.replace("/", r"/\allowbreak{}")
    return s.replace("chi2", r"$\chi^2$").replace("~", r"$\sim$")


def sections(s: str) -> str:
    return r"\newline ".join(p.strip() for p in s.split(",") if p.strip())


def year(r: dict) -> int:
    m = re.search(r"\d{4}", r["key"])
    return int(m.group()) if m else 9999


def main() -> None:
    rows = [r for r in csv.DictReader(SRC.open()) if r["setting"] != "review"]
    rows.sort(key=year)
    spec = "".join(f">{{\\raggedright\\arraybackslash}}p{{{w}}}" for _, w, _ in COLUMNS)
    head = " & ".join(rf"\textbf{{{h}}}" for h, _, _ in COLUMNS) + r" \\"
    ncol = len(COLUMNS)
    caption = (
        r"\caption{Supplementary evidence matrix: experimental studies of rodent receivers "
        r"cited in this review, in chronological order. Setting: lab; field; or semi "
        r"(wild-caught animals tested in captivity or semi-natural conditions). nr, not "
        r"reported in the sources consulted for this draft. Sec., manuscript section(s) "
        r"where the study informs the argument (S2 features; S3 mechanisms; S4 action; "
        r"S5 persistence; S6 integrated account). Limitations and verification status "
        r"for each study are in tables/evidence\_matrix.csv.}"
        r"\label{tab:evidence-supp} \\"
    )
    lines = [
        "% Generated by scripts/make_table.py from tables/evidence_matrix.csv. Do not edit by hand.",
        r"\begin{landscape}",
        r"\begingroup",
        r"\scriptsize",
        r"\singlespacing",
        r"\setlength{\tabcolsep}{3pt}",
        r"\setlength{\LTcapwidth}{\linewidth}",
        r"\renewcommand{\arraystretch}{1.15}",
        rf"\begin{{longtable}}{{{spec}}}",
        caption,
        r"\toprule",
        head,
        r"\midrule",
        r"\endfirsthead",
        rf"\multicolumn{{{ncol}}}{{@{{}}l}}{{\textit{{Table~\ref{{tab:evidence-supp}}, continued}}}} \\",
        r"\toprule",
        head,
        r"\midrule",
        r"\endhead",
        r"\bottomrule",
        r"\endlastfoot",
    ]
    for i, r in enumerate(rows):
        shade = r"\rowcolor{black!5}" if i % 2 else ""
        lines.append(shade + " & ".join(f(r) for _, _, f in COLUMNS) + r" \\")
    lines += [r"\end{longtable}", r"\endgroup", r"\end{landscape}", ""]
    text = "\n".join(lines)
    for out in OUTS:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)
        print(f"wrote {out} ({len(rows)} rows)")


if __name__ == "__main__":
    main()
