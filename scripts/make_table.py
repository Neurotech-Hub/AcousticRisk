"""Build Table 1 (comparative evidence matrix) from the CSV source.

Source of truth: manuscript/tables/evidence_matrix.csv (edit that, not the .tex).
Run from the repository root: python3 scripts/make_table.py
"""
import csv
from pathlib import Path

SRC = Path("manuscript/tables/evidence_matrix.csv")
OUT = Path("manuscript/tables/table1_evidence.tex")

COLUMNS = [
    # (header, width, row -> cell)
    ("Study", "1.0in", lambda r: rf"\citet{{{r['key']}}}"),
    ("Species (setting)", "1.1in", lambda r: f"{tex(r['species'])} ({r['setting']})"),
    ("Receiver experience", "0.9in", lambda r: tex(r["experience"])),
    ("Stimuli; controls", "1.7in", lambda r: f"{tex(r['stimuli'])}; {tex(r['controls'])}"),
    ("Endpoints", "1.3in", lambda r: tex(r["endpoints"])),
    ("Key result", "1.9in", lambda r: tex(r["result"])),
    ("Q", "0.3in", lambda r: tex(r["questions"]).replace("Q", "")),
]


def tex(s: str) -> str:
    s = s.replace("\\", r"\textbackslash{}")
    for a, b in [("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_")]:
        s = s.replace(a, b)
    return s.replace("chi2", r"$\chi^2$").replace("~", r"$\sim$")


def main() -> None:
    rows = list(csv.DictReader(SRC.open()))
    spec = "".join(f">{{\\raggedright\\arraybackslash}}p{{{w}}}" for _, w, _ in COLUMNS)
    head = " & ".join(rf"\textbf{{{h}}}" for h, _, _ in COLUMNS) + r" \\"
    lines = [
        "% Generated by scripts/make_table.py from tables/evidence_matrix.csv. Do not edit by hand.",
        r"\begin{landscape}",
        r"\begingroup",
        r"\footnotesize",
        r"\singlespacing",
        r"\setlength{\tabcolsep}{4pt}",
        rf"\begin{{longtable}}{{{spec}}}",
        r"\caption{Comparative evidence matrix: experimental studies of rodent receivers cited in this review, in "
        r"chronological order. Setting: lab, field, or semi (wild-caught animals tested in captivity or semi-natural "
        r"conditions). nr, not reported in the sources consulted for this draft. Q, review question(s) addressed. "
        r"The full matrix, including limitations and verification status, is in tables/evidence\_matrix.csv.}"
        r"\label{tab:evidence} \\",
        r"\toprule",
        head,
        r"\midrule",
        r"\endfirsthead",
        r"\toprule",
        head,
        r"\midrule",
        r"\endhead",
        r"\bottomrule",
        r"\endlastfoot",
    ]
    for r in rows:
        lines.append(" & ".join(f(r) for _, _, f in COLUMNS) + r" \\ \addlinespace[3pt]")
    lines += [r"\end{longtable}", r"\endgroup", r"\end{landscape}", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(rows)} rows)")


if __name__ == "__main__":
    main()
